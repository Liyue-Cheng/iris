interface ContextHookAdapter {
  id: string;
  label: string;
  dir: string; // config dir under home — its presence is the install signal
  file: string; // settings file inside that dir
  /** Key inside hooks{} — Claude-compatible everywhere except Cursor's casing. */
  hookKey: string;
}

/** App-owned context adapters, independent from the user launcher list. */
function contextHookAdapters(): ContextHookAdapter[] {
  const home = homedir();
  return [
    { id: 'claude', label: 'Claude Code', dir: join(home, '.claude'), file: 'settings.json', hookKey: 'SessionStart' },
    { id: 'gemini', label: 'Gemini CLI', dir: join(home, '.gemini'), file: 'settings.json', hookKey: 'SessionStart' },
    { id: 'qwen', label: 'Qwen Code', dir: join(home, '.qwen'), file: 'settings.json', hookKey: 'SessionStart' },
    { id: 'cursor', label: 'Cursor CLI', dir: join(home, '.cursor'), file: 'cli.json', hookKey: 'sessionStart' },
    // Codex supports the same hook schema in a user-level hooks.json. Keeping
    // it separate from config.toml avoids rewriting hand-maintained settings.
    { id: 'codex', label: 'Codex CLI', dir: join(home, '.codex'), file: 'hooks.json', hookKey: 'SessionStart' },
  ];
}

async function exists(p: string): Promise<boolean> {
  try {
    await fs.access(p);
    return true;
  } catch {
    return false;
  }
}

/** A handler counts as ours iff its command mentions Iris's generated script. */
function isIrisHandler(value: unknown): value is Record<string, unknown> {
  if (!value || typeof value !== 'object') return false;
  const command = (value as Record<string, unknown>)['command'];
  return typeof command === 'string' && command.includes('focus-context.ps1');
}

function eventHandlers(config: Record<string, unknown>, hookKey: string): unknown[] {
  const hooks = config['hooks'];
  if (!hooks || typeof hooks !== 'object') return [];
  const groups = (hooks as Record<string, unknown>)[hookKey];
  if (!Array.isArray(groups)) return [];
  return groups.flatMap((group) => {
    if (!group || typeof group !== 'object') return [];
    const handlers = (group as Record<string, unknown>)['hooks'];
    return Array.isArray(handlers) ? handlers : [];
  });
}

export async function injectionState(): Promise<InjectionState> {
  const clis: HookCliInfo[] = [];

  for (const cli of contextHookAdapters()) {
    const configPath = join(cli.dir, cli.file);
    if (!(await exists(cli.dir))) {
      clis.push({ id: cli.id, label: cli.label, configPath, state: 'cli-not-found' });
      continue;
    }
    let state: HookCliState = 'not-configured';
    try {
      const text = await fs.readFile(configPath, 'utf8');
      const config = JSON.parse(text) as Record<string, unknown>;
      const ours = eventHandlers(config, cli.hookKey).filter(isIrisHandler);
      if (ours.length > 0) {
        state = ours.every(
          (handler) => handler['type'] === 'command' && handler['command'] === hookCommand(),
        )
          ? 'configured'
          : 'stale';
      }
    } catch {
      /* missing or unparsable settings file → treat as not configured */
    }
    clis.push({ id: cli.id, label: cli.label, configPath, state });
  }

  const codex = clis.find((cli) => cli.id === 'codex');
  if (codex) {
    codex.detail = mainT('settings.codexHookDetail');
  }

  return {
    script: {
      path: focusScriptPath(),
      state: await focusScriptState(),
      hookCommand: hookCommand(),
    },
    clis,
  };
}

/** Write (or refresh) the machine-level script. App-owned — overwrite OK.
 *  Written with a UTF-8 BOM (\\uFEFF): Windows PowerShell 5.1 only detects
 *  UTF-8 via the BOM, else it reads the file as the system ANSI codepage and
 *  the Chinese text / em-dashes break the parse (the SessionStart hook error
 *  reported at focus-context.ps1:17). */
const UTF8_BOM = String.fromCharCode(0xfeff); // U+FEFF — see installFocusScript

async function focusScriptState(
  path = focusScriptPath(),
): Promise<'missing' | 'stale' | 'current'> {
  try {
    const text = await fs.readFile(path, 'utf8');
    return text === UTF8_BOM + FOCUS_CONTEXT_SCRIPT ? 'current' : 'stale';
  } catch {
    return 'missing';
  }
}

async function writeFocusScript(path: string): Promise<void> {
  await fs.mkdir(dirname(path), { recursive: true });
  await fs.writeFile(path, UTF8_BOM + FOCUS_CONTEXT_SCRIPT, 'utf8');
  logger.info('agent', `focus-context script written: ${path}`);
}

/**
 * Keep Iris's machine script current without user intervention. Hook configs
 * are user-owned and remain confirmation-gated; this generated file is
 * app-owned and every installed version points to the same stable path, so
 * allowing a stale copy to run only creates a split-brain runtime.
 */
export async function ensureFocusScriptCurrent(
  path = focusScriptPath(),
): Promise<{ path: string; action: 'created' | 'updated' | 'unchanged' }> {
  const state = await focusScriptState(path);
  if (state === 'current') return { path, action: 'unchanged' };
  await writeFocusScript(path);
  return { path, action: state === 'missing' ? 'created' : 'updated' };
}

/** Explicit recovery endpoint retained for IPC/backward compatibility. */
export async function installFocusScript(): Promise<{ path: string }> {
  const path = focusScriptPath();
  await writeFocusScript(path);
  return { path };
}

// ──────────────────────────────────────────────────────────────────
// Static leg — the `<iris-software>` managed block in entry files (§3A).
