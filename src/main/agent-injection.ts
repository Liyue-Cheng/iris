export interface EntrySyncResult {
  /** Whether the file existed before this write. */
  existed: boolean;
  action: Exclude<UpsertAction, 'removed'>;
}

/**
 * Insert or refresh the `<iris-software>` block in one entry file, preserving
 * everything outside it. Writes only when the block actually changes (no
 * needless file-watcher echo). Does NOT create the file's parent unless we're
 * actually writing.
 */
export async function syncEntryFile(absPath: string): Promise<EntrySyncResult> {
  let existed = true;
  let current = '';
  try {
    current = await fs.readFile(absPath, 'utf8');
  } catch {
    existed = false;
  }
  const { text, action } = upsertSoftwareBlock(current);
  if (action !== 'unchanged') {
    await fs.mkdir(dirname(absPath), { recursive: true });
    await fs.writeFile(absPath, text, 'utf8');
    logger.info('agent', `software block ${action} in ${absPath}`);
  }
  return { existed, action };
}

