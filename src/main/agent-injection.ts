import type { ContextPreview, HookCliInfo, HookCliState, InjectionState } from '@shared/types';
import { irisHomeDir } from './settings-manager';
import {
  buildSoftwareBlock,
  parseProjectBlock,
  parseSoftwareBlock,
  removeSoftwareBlock,
  upsertProjectBlock,
  upsertSoftwareBlock,
  type UpsertAction,
} from './software-prompt';
