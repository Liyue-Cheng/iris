/** ~/.iris/focus-context.ps1 — always the REAL ~/.iris (hooks written into
 *  agent configs must keep working whether Iris runs as dev or packaged). */
export function focusScriptPath(): string {
  return join(irisHomeDir(), 'focus-context.ps1');
}

/**
 * The script itself (prompt-governance 动态腿, §3B): document sessions carry
 * FOCUS_DOC and workspace hubs carry IRIS_WORKSPACE_PATH. Both inline the
 * dynamic context layers; document
 * sessions additionally include the focused doc, while hubs emit workspace
 * metadata only. Static software/project prompts already come from the entry
 * file; the hook adds only workspace/focus context. The focus doc degrades to a pointer above 32 KiB. A random
 * terminal with neither Iris variable prints nothing.
 *
 * Written with a UTF-8 BOM so Windows PowerShell 5.1 parses the non-ASCII text
 * (without a BOM it reads the file as the system ANSI codepage — GBK on a
 * Chinese Windows — and mangles every multibyte char). The OutputEncoding line
 * forces stdout to UTF-8 so the injected context is not mojibake either. PS
 * strings are single-quoted / concatenated to avoid backtick escapes colliding
 * with this JS template literal.
 */
export const FOCUS_CONTEXT_SCRIPT = `# Iris focus-context (machine layer, generated by Iris — editing is fine)
# SessionStart-hook payload: reads FOCUS_DOC or IRIS_WORKSPACE_PATH (set by
# Iris when spawning a terminal) and inlines dynamic context.
[Console]::OutputEncoding = [System.Text.Encoding]::UTF8
$focus = $env:FOCUS_DOC
$workspace = $env:IRIS_WORKSPACE_PATH
if (-not $focus -and -not $workspace) { exit 0 }
$root = (Get-Location).Path

# Keep the first character non-JSON: Codex otherwise treats a leading '[' as
# a JSON array and reports "invalid session start JSON" instead of using text.
if ($focus) {
  Write-Output ('Iris: This terminal was started by Iris; project root: ' + $root + '; focused document: ' + $focus)
} else {
  Write-Output ('Iris: This terminal was started by Iris; project root: ' + $root + '; workspace: ' + $workspace)
  Write-Output ('<iris-workspace path="' + $workspace + '">')
  if ($workspace -eq '.iris') {
    Write-Output 'This is a project-root hub session. It was opened from the project root and is not focused on any document. FOCUS_DOC is unset, and no actual <iris-focus> block is injected. Do not read or infer a focused document; wait for the user''s instruction.'
  } else {
    Write-Output ('This is a workspace hub session opened from ' + $workspace + '. It is not focused on any document. FOCUS_DOC is unset, and no actual <iris-focus> block is injected. Do not read or infer a focused document; wait for the user''s instruction.')
  }
  Write-Output '</iris-workspace>'
}
Write-Output 'The injected layers follow. Environment variables and reading files from disk are fallbacks only: do not re-read content already injected unless you have reason to believe it changed. The content below is a snapshot taken at session start.'

# focused document — snapshot, degrade to a pointer above 32 KiB. Hub
# sessions intentionally omit the entire iris-focus block.
if ($focus) {
  $doc = Join-Path $root $focus
  Write-Output ('<iris-focus path="' + $focus + '">')
  if (Test-Path -LiteralPath $doc) {
    $size = (Get-Item -LiteralPath $doc).Length
    if ($size -le 32768) {
      Get-Content -Raw -LiteralPath $doc -Encoding UTF8
    } else {
      Write-Output ('The focused document exceeds 32 KiB (' + $size + ' bytes), so its contents were not inlined. Read the file directly.')
    }
  } else {
    Write-Output 'The focused document is not currently on disk and may have been moved or deleted. Keep the path as context and wait for the user''s instruction.'
  }
  Write-Output '</iris-focus>'
}
`;

/** The one command every JSON-hook CLI gets pointed at. */
export function hookCommand(): string {
  return `powershell -NoProfile -ExecutionPolicy Bypass -File "${focusScriptPath()}"`;
}

