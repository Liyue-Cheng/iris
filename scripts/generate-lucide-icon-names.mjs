import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import dynamicIconImports from 'lucide-react/dynamicIconImports.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const target = resolve(root, 'src/shared/lucide-icon-names.ts');
const names = Object.keys(dynamicIconImports).sort();
const source = `// Generated by scripts/generate-lucide-icon-names.mjs. Do not edit manually.\nexport const LUCIDE_ICON_NAMES = ${JSON.stringify(names, null, 2)} as const;\n`;

writeFileSync(target, source, 'utf8');
console.log(`wrote ${names.length} Lucide icon names to src/shared/lucide-icon-names.ts`);
